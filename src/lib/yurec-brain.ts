export type ChatMode = "yurec" | "sms";
export type YurecMood = "calm" | "drunk" | "psycho";

export type ChatMsg = {
  role: "user" | "yurec";
  text: string;
};

function fold(s: string) {
  return String(s || "")
    .toLowerCase()
    .replace(/ё/g, "е");
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]!;
}

function has(t: string, keys: string[]) {
  return keys.some((k) => t.includes(k));
}

function clip(s: string, n: number) {
  const t = String(s || "").replace(/\s+/g, " ").trim();
  return t.length > n ? t.slice(0, n) : t;
}

export function detectMood(messages: ChatMsg[]): YurecMood {
  const blob = fold(messages.slice(-6).map((m) => m.text).join(" "));
  if (has(blob, ["нло", "ящер", "рептил", "купол", "заговор", "следят", "украл", "тарелк", "сенсор заговор", "чип", "прослуш"])) {
    return "psycho";
  }
  if (has(blob, ["водк", "бух", "пьян", "толян", "ларек", "ларёк", "рюм", "надрать", "пол-литр", "поллитр", "беленьк", "путинк"])) {
    return "drunk";
  }
  return "calm";
}

export function trimYurec(text: string, mode: ChatMode): string {
  let t = String(text || "").replace(/\s+\n/g, "\n").trim();
  t = t.replace(/^["«]+|["»]+$/g, "").trim();
  if (!t) return "";
  if (mode === "sms") {
    return t
      .split(/\n/)
      .map((x) => x.trim())
      .filter(Boolean)
      .slice(0, 3)
      .join("\n")
      .slice(0, 220);
  }
  const parts = t.split(/(?<=[.!?…])\s+/).filter(Boolean);
  t = parts.slice(0, 3).join(" ");
  if (t.length > 280) t = t.slice(0, 277).replace(/\s+\S*$/, "") + "…";
  return t;
}

