function wantsStory(t: string, raw: string) {
  if (raw.trim().length >= 90) return true;
  return has(t, ["представь", "а если", "история", "расскажи", "позвон", "сегодня", "вчера", "слушай", "короче было", "новая серия", "зашквар"]);
}

function improvise(mode: ChatMode, userText: string, mood: YurecMood): string {
  const seed = clip(userText.replace(/\s+/g, " "), 70);
  if (mode === "sms") {
    if (mood === "psycho") return `кароч ${seed} это заговор зины и нло я гранату ближе подвинул лол`;
    if (mood === "drunk") return `слышь ${seed} толян налил в долг я гошу покормил дальше не помню но я легенда`;
    return `кароч слушай ${seed} я б это косте с флай орнул да светка не берёт двор уже ржёт`;
  }
  if (mood === "psycho") {
    return `Слышь. «${seed}» — не случайность. Зина уже в курсе, тарелка над баком. Граната ближе к подушке.`;
  }
  if (mood === "drunk") {
    return `Слышь… ${seed}. Толян ещё одну в долг налил, Гошу покормил. Дальше дырка, но я легенда.`;
  }
  return `Алё. ${seed} — готовая серия. Я б Косте с Fly орнул, да Светка опять не берёт. Двор уже ржёт, я царь.`;
}

function tint(line: string, mood: YurecMood, mode: ChatMode): string {
  if (mode === "sms") return line;
  if (mood === "drunk" && !/толян|пол-литр|водк/i.test(line)) {
    return line.replace(/\.*$/, "") + " Толян б ещё налил бы.";
  }
  if (mood === "psycho" && !/нло|ящер|зин/i.test(line)) {
    return line.replace(/\.*$/, "") + " Зина это слышала, сто пудов.";
  }
  return line;
}

export function localYurecReply(mode: ChatMode, userText: string, history: ChatMsg[] = []): string {
  const t = fold(userText);
  const mood = detectMood([...history, { role: "user", text: userText }]);
  if (wantsStory(t, userText)) return improvise(mode, userText, mood);
  const pool = mode === "sms" ? SMS_LINES : YUREC_LINES;
  const topic = topicOf(t);
  const lines = pool[topic] || pool.default;
  return tint(pick(lines), mood, mode);
}

export function welcomeLine(mode: ChatMode): string {
  return mode === "sms"
    ? "прив это юрец пиши чо хош я тута бета кароч не ругайся если туплю"
    : "Алё. Юрец на проводе. Бета, Fly может залагать. Говори по делу — я не лектор.";
}
